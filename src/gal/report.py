# Fixed categorical order (validated reference palette); colour follows the entity.
PALETTE = ("#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#6250d6", "#e34948")
INK = "#0b0b0b"
INK_2 = "#52514e"
GRID = "#e4e3df"
SURFACE = "#fcfcfb"
TRUTH_COLOR = "#3a3a38"

FOCUS_MODELS: tuple[str, ...] = (
    "last_touch",
    "first_touch",
    "linear",
    "w_shaped",
    "markov_o1",
    "shapley_empirical",
    "shapley_model",
)
MODEL_COLOR = {m: PALETTE[i] for i, m in enumerate(FOCUS_MODELS)}

SYNTHETIC_BANNER = (
    "All data in this report is SYNTHETIC, generated by gtm-attribution-lab with a known "
    "causal ground truth. Numbers describe the simulator, not any real company."
)


def _style(ax: Any) -> None:
    ax.set_facecolor(SURFACE)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_2, labelsize=9)
    ax.grid(axis="y", color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def _new(figsize: tuple[float, float] = (8.0, 4.2)) -> tuple[Figure, Any]:
    fig, ax = plt.subplots(figsize=figsize, dpi=110)
    fig.patch.set_facecolor(SURFACE)
    _style(ax)
    return fig, ax


def _png(fig: Figure) -> bytes:
    buf = io.BytesIO()
    fig.tight_layout()
    fig.savefig(buf, format="png", facecolor=SURFACE)
    plt.close(fig)
    return buf.getvalue()


