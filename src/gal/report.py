def _fmt(v: Any) -> str:
    if isinstance(v, float | np.floating):
        f = float(v)
        if not np.isfinite(f):
            return "n/a"
        if f != 0 and abs(f) < 0.001:
            return f"{f:.2e}"
        return f"{f:,.3f}" if abs(f) < 1000 else f"{f:,.0f}"
    if isinstance(v, pd.Timestamp):
        return str(v.strftime("%Y-%m-%d"))
    return str(v)


def md_table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    rows = ["| " + " | ".join(_fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def html_table(df: pd.DataFrame) -> str:
    head = "".join(f"<th>{html.escape(str(c))}</th>" for c in df.columns)
    body = "".join(
        "<tr>" + "".join(f"<td>{html.escape(_fmt(v))}</td>" for v in row) + "</tr>"
        for row in df.itertuples(index=False)
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def validation_table(summary: pd.DataFrame, level: str = "account") -> pd.DataFrame:
    s = summary[summary.level == level].copy()
    s["MAE (95% CI)"] = [
        f"{m:.3f} [{lo:.3f}, {hi:.3f}]"
        for m, lo, hi in zip(s.mae_mean, s.mae_ci_low, s.mae_ci_high, strict=True)
    ]
    s["Spearman (95% CI)"] = [
        "n/a" if not np.isfinite(m) else f"{m:.2f} [{lo:.2f}, {hi:.2f}]"
        for m, lo, hi in zip(s.spearman_mean, s.spearman_ci_low, s.spearman_ci_high, strict=True)
    ]
    s["direct share"] = s.direct_share_mean
    return s[
        ["confounding", "model", "n_seeds", "MAE (95% CI)", "Spearman (95% CI)", "direct share"]
    ]


