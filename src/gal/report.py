def fig_credit_vs_truth(attribution: pd.DataFrame, gt: GroundTruth) -> bytes:
    acc = attribution[attribution["level"] == "account"]
    channels = list(gt.channels)
    models = [
        m for m in ("last_touch", "linear", "markov_o1", "shapley_model") if m in set(acc.model)
    ]
    fig, ax = _new((9.0, 4.4))
    width = 0.8 / (len(models) + 1)
    x = np.arange(len(channels))
    ax.bar(x, [gt.share[c] for c in channels], width * 0.9, color=TRUTH_COLOR, label="ground truth")
    for i, m in enumerate(models):
        share = acc[acc.model == m].set_index("channel")["share"]
        ax.bar(
            x + (i + 1) * width,
            [float(share.get(c, 0.0)) for c in channels],
            width * 0.9,
            color=MODEL_COLOR[m],
            label=m,
        )
    ax.set_xticks(x + width * len(models) / 2, channels, rotation=15)
    ax.set_ylabel("share of credit", color=INK_2)
    ax.set_title("Channel credit vs. true incremental share (account level, one run)", color=INK)
    ax.legend(frameon=False, fontsize=8, ncol=5)
    return _png(fig)


def fig_mae_by_confounding(summary: pd.DataFrame) -> bytes:
    acc = summary[summary["level"] == "account"]
    fig, ax = _new()
    for m in FOCUS_MODELS:
        g = acc[acc.model == m].sort_values("confounding")
        if g.empty:
            continue
        yerr = np.vstack([g.mae_mean - g.mae_ci_low, g.mae_ci_high - g.mae_mean])
        ax.errorbar(
            g.confounding,
            g.mae_mean,
            yerr=yerr,
            color=MODEL_COLOR[m],
            marker="o",
            markersize=5,
            linewidth=2,
            capsize=3,
            label=m,
        )
    uni = acc[acc.model == "uniform"].sort_values("confounding")
    if not uni.empty:
        ax.plot(
            uni.confounding,
            uni.mae_mean,
            color=INK_2,
            linestyle="--",
            linewidth=1.5,
            label="uniform (reference)",
        )
    ax.set_xlabel("intent confounding strength", color=INK_2)
    ax.set_ylabel("MAE of channel shares (lower = better)", color=INK_2)
    ax.set_title("Attribution error vs. confounding (mean and 95% CI across seeds)", color=INK)
    ax.legend(frameon=False, fontsize=8, ncol=2)
    return _png(fig)


def fig_level_comparison(summary: pd.DataFrame, confounding: float) -> bytes:
    s = summary[np.isclose(summary.confounding, confounding)]
    models = [m for m in FOCUS_MODELS if m in set(s.model)]
    fig, ax = _new()
    x = np.arange(len(models))
    for j, (level, color) in enumerate((("account", PALETTE[0]), ("contact", PALETTE[1]))):
        g = s[s.level == level].set_index("model")
        means = [float(g.loc[m, "mae_mean"]) for m in models]
        lo = [float(g.loc[m, "mae_mean"] - g.loc[m, "mae_ci_low"]) for m in models]
        hi = [float(g.loc[m, "mae_ci_high"] - g.loc[m, "mae_mean"]) for m in models]
        ax.bar(
            x + j * 0.4,
            means,
            0.38,
            yerr=[lo, hi],
            color=color,
            capsize=3,
            label=f"{level}-level",
            error_kw={"ecolor": INK_2, "elinewidth": 1},
        )
    ax.set_xticks(x + 0.2, models, rotation=15)
    ax.set_ylabel("MAE of channel shares", color=INK_2)
    ax.set_title(f"Account- vs contact-level journeys (confounding = {confounding})", color=INK)
    ax.legend(frameon=False, fontsize=8)
    return _png(fig)


def fig_control(control: pd.DataFrame) -> bytes:
    acc = control[control.level == "account"].sort_values("mae_mean")
    fig, ax = _new()
    colors = [MODEL_COLOR.get(m, GRID if m != "uniform" else INK_2) for m in acc.model]
    lo = acc.mae_mean - acc.mae_ci_low
    hi = acc.mae_ci_high - acc.mae_mean
    ax.barh(
        acc.model,
        acc.mae_mean,
        xerr=[lo, hi],
        color=colors,
        capsize=3,
        error_kw={"ecolor": INK_2, "elinewidth": 1},
    )
    ax.invert_yaxis()
    ax.grid(axis="x", color=GRID)
    ax.grid(axis="y", visible=False)
    ax.set_xlabel("MAE of channel shares (lower = better)", color=INK_2)
    ax.set_title("Positive control: a world that satisfies path-model assumptions", color=INK)
    return _png(fig)


def fig_convergence(points: Sequence[tuple[int, float]]) -> bytes:
    fig, ax = _new((7.0, 4.0))
    m = np.array([p[0] for p in points], dtype=float)
    err = np.array([p[1] for p in points], dtype=float)
    ax.loglog(m, err, marker="o", color=PALETTE[0], linewidth=2, label="Monte-Carlo vs exact")
    ref = err[0] * np.sqrt(m[0] / m)
    ax.loglog(m, ref, linestyle="--", color=INK_2, linewidth=1.2, label=r"$1/\sqrt{m}$ reference")
    ax.set_xlabel("sampled permutations m", color=INK_2)
    ax.set_ylabel("mean |phi_MC - phi_exact|", color=INK_2)
    ax.set_title("Shapley Monte-Carlo convergence (8-player channel response game)", color=INK)
    ax.legend(frameon=False, fontsize=8)
    return _png(fig)


def fig_cohorts(cohorts: pd.DataFrame) -> bytes:
    cols = ["lead_to_mql", "mql_to_sql", "sql_to_opp", "opp_to_won", "lead_to_won"]
    data = cohorts[cols].to_numpy(dtype=float)
    fig, ax = plt.subplots(figsize=(8.0, 4.4), dpi=110)
    fig.patch.set_facecolor(SURFACE)
    im = ax.imshow(data, cmap="Blues", aspect="auto", vmin=0, vmax=max(0.8, float(np.nanmax(data))))
    ax.set_xticks(range(len(cols)), cols, fontsize=9, color=INK_2)
    labels = [pd.Timestamp(c).strftime("%Y-%m") for c in cohorts.cohort_month]
    ax.set_yticks(range(len(labels)), labels, fontsize=9, color=INK_2)
    for i in range(data.shape[0]):
        for j in range(data.shape[1]):
            v = data[i, j]
            if np.isfinite(v):
                ax.text(
                    j,
                    i,
                    f"{v:.0%}",
                    ha="center",
                    va="center",
                    fontsize=8,
                    color="white" if v > 0.5 else INK,
                )
    ax.set_title("Stage conversion by monthly lead cohort (late cohorts still maturing)", color=INK)
    fig.colorbar(im, ax=ax, fraction=0.03)
    return _png(fig)


def fig_km(funnel: pd.DataFrame, data_end: pd.Timestamp) -> bytes:
    fig, ax = _new()
    for i, stage in enumerate(STAGE_COLUMNS):
        km = time_to_stage(funnel, stage, data_end)
        ax.step(km.times, 1 - km.survival, where="post", color=PALETTE[i], linewidth=2, label=stage)
        ax.fill_between(
            km.times,
            1 - km.ci_low,
            1 - km.ci_high,
            step="post",
            color=PALETTE[i],
            alpha=0.15,
            linewidth=0,
        )
    ax.set_xlabel("days since lead created", color=INK_2)
    ax.set_ylabel("share of leads that reached stage", color=INK_2)
    ax.set_title("Time-to-stage, Kaplan-Meier (1 - S(t), 95% Greenwood band)", color=INK)
    ax.legend(frameon=False, fontsize=8)
    return _png(fig)


