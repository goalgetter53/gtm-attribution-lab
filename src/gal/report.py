@dataclass
class Section:
    title: str
    text: str
    figure: str | None = None
    table: pd.DataFrame | None = None


@dataclass
class Report:
    title: str
    sections: list[Section] = field(default_factory=list)
    figures: dict[str, bytes] = field(default_factory=dict)

    def to_html(self) -> str:
        parts = [
            "<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>",
            f"<title>{html.escape(self.title)}</title>",
            "<style>body{font-family:system-ui,-apple-system,Segoe UI,sans-serif;max-width:980px;"
            f"margin:2rem auto;padding:0 1rem;color:{INK};background:{SURFACE};line-height:1.5}}"
            ".banner{background:#fff4d6;border:1px solid #eda100;padding:.75rem 1rem;"
            "border-radius:6px}"
            "table{border-collapse:collapse;font-size:.85rem;margin:.75rem 0}"
            f"th,td{{border-bottom:1px solid {GRID};padding:.3rem .6rem;text-align:right}}"
            "th:first-child,td:first-child{text-align:left}"
            "img{max-width:100%}h2{margin-top:2.2rem}</style></head><body>",
            f"<h1>{html.escape(self.title)}</h1>",
            "<p class='banner'><strong>Synthetic data.</strong> "
            f"{html.escape(SYNTHETIC_BANNER)}</p>",
        ]
        for s in self.sections:
            parts.append(f"<h2>{html.escape(s.title)}</h2>")
            parts.extend(f"<p>{html.escape(p)}</p>" for p in s.text.split("\n\n") if p.strip())
            if s.figure:
                b64 = base64.b64encode(self.figures[s.figure]).decode("ascii")
                parts.append(
                    f"<img alt='{html.escape(s.title)}' src='data:image/png;base64,{b64}'>"
                )
            if s.table is not None:
                parts.append(html_table(s.table))
        parts.append("</body></html>")
        return "\n".join(parts)

    def to_markdown(self, figure_dir: str = "figures") -> str:
        out = [f"# {self.title}", "", f"> **Synthetic data.** {SYNTHETIC_BANNER}", ""]
        for s in self.sections:
            out += [f"## {s.title}", "", s.text, ""]
            if s.figure:
                out += [f"![{s.title}]({figure_dir}/{s.figure}.png)", ""]
            if s.table is not None:
                out += [md_table(s.table), ""]
        return "\n".join(out)

    def write(self, out_dir: str | Path) -> tuple[Path, Path]:
        out = Path(out_dir)
        (out / "figures").mkdir(parents=True, exist_ok=True)
        for name, png in self.figures.items():
            (out / "figures" / f"{name}.png").write_bytes(png)
        html_path = out / "report.html"
        md_path = out / "report.md"
        html_path.write_text(self.to_html(), encoding="utf-8")
        md_path.write_text(self.to_markdown(), encoding="utf-8")
        return html_path, md_path


def shapley_convergence_points(
    journeys: Sequence[Any], seed: int = 0, sizes: Sequence[int] = (10, 30, 100, 300, 1000, 3000)
) -> list[tuple[int, float]]:
    """MC-vs-exact error on the population-level response game (mean predicted lift)."""
    model = fit_response_model(journeys)
    games = [model.game(j) for j in journeys if not j.is_empty][:400]
    players = list(model.channels)

    def v(s: frozenset[str]) -> float:
        return float(np.mean([g(s) for g in games]))

    return mc_convergence(players, v, sizes, np.random.default_rng(seed), repeats=3)


def build_report(
    con: Any,
    gt: GroundTruth,
    attribution: pd.DataFrame,
    data_end_day: int,
    journeys: Sequence[Any],
    validation_summary: pd.DataFrame | None = None,
    control_summary: pd.DataFrame | None = None,
    reference_confounding: float | None = None,
) -> Report:
    rep = Report(title="gtm-attribution-lab report")
    data_end = EPOCH + pd.Timedelta(days=data_end_day)

    ident = con.execute("select * from marts.mart_identity_coverage").df().iloc[0]
    channels = con.execute("select * from marts.mart_channel_summary").df()
    rep.sections.append(
        Section(
            "1. Data and identity resolution",
            f"{int(ident.web_sessions):,} web sessions, of which "
            f"{int(ident.identified_sessions):,} "
            f"({ident.identified_sessions / ident.web_sessions:.0%}) "
            f"were stitched to a known contact; {int(ident.direct_sessions):,} sessions landed as "
            f"'direct' (missing UTM/referrer or genuinely untracked). "
            f"{int(ident.contacts_domain_matched):,} contacts were matched to accounts by email "
            f"domain and {int(ident.contacts_unresolved):,} stayed unresolved. "
            f"Realised wins in this run: {gt.realized_wins}; expected wins under the simulator: "
            f"{gt.expected_wins:.1f}.",
            table=channels,
        )
    )

    rep.figures["credit_vs_truth"] = fig_credit_vs_truth(attribution, gt)
    acc = attribution[attribution.level == "account"].pivot(
        index="model", columns="channel", values="share"
    )
    acc = acc[list(gt.channels)]
    truth_row = pd.DataFrame([gt.share], index=["GROUND TRUTH"])[list(gt.channels)]
    tbl = pd.concat([truth_row, acc]).reset_index().rename(columns={"index": "model"})
    rep.sections.append(
        Section(
            "2. Who gets the credit? (single run, account level)",
            "Ground truth is the share of expected wins that disappear when a channel's touches "
            "are removed from the simulator (common-random-number counterfactual). Model shares "
            "exclude credit given to 'direct', which has no causal ground truth.",
            figure="credit_vs_truth",
            table=tbl,
        )
    )

    if validation_summary is not None and not validation_summary.empty:
        rep.figures["mae_by_confounding"] = fig_mae_by_confounding(validation_summary)
        rep.sections.append(
            Section(
                "3. Validation across seeds and confounding levels",
                "MAE = mean absolute difference between a model's channel shares and the true "
                "incremental shares; Spearman = rank agreement. Intervals are 95% t-intervals "
                "across seeds. 'uniform' gives every channel the same share and is the bar a model "
                "must clear to be informative.",
                figure="mae_by_confounding",
                table=validation_table(validation_summary, "account"),
            )
        )
        conf = (
            reference_confounding
            if reference_confounding is not None
            else float(
                sorted(validation_summary.confounding.unique())[
                    len(validation_summary.confounding.unique()) // 2
                ]
            )
        )
        rep.figures["account_vs_contact"] = fig_level_comparison(validation_summary, conf)
        rep.sections.append(
            Section(
                "4. Account-level vs contact-level journeys",
                "Contact-level journeys only follow the opportunity's primary contact, so touches "
                "on the rest of the buying committee are invisible to the model.",
                figure="account_vs_contact",
                table=validation_table(validation_summary, "contact"),
            )
        )
    if control_summary is not None and not control_summary.empty:
        rep.figures["positive_control"] = fig_control(control_summary)
        rep.sections.append(
            Section(
                "5. Positive control",
                "Same engine, a world built to satisfy path-model assumptions (no confounding, "
                "no tracking noise, one effective transition). Models that recover the truth here "
                "but not in the realistic world are being broken by the world, not by a bug.",
                figure="positive_control",
                table=validation_table(control_summary, "account"),
            )
        )

    points = shapley_convergence_points(journeys)
    rep.figures["shapley_convergence"] = fig_convergence(points)
    rep.sections.append(
        Section(
            "6. Shapley Monte-Carlo convergence",
            "Exact Shapley enumerates 2^n coalitions; with many channels the lab samples "
            "permutations instead. Error against the exact solution falls at the expected "
            "1/sqrt(m) rate.",
            figure="shapley_convergence",
            table=pd.DataFrame(points, columns=["permutations", "mean_abs_error"]),
        )
    )

    cohorts = con.execute("select * from marts.mart_funnel_cohorts").df()
    rep.figures["funnel_cohorts"] = fig_cohorts(cohorts)
    rep.sections.append(
        Section(
            "7. Funnel conversion by cohort",
            "Monthly lead cohorts, stage-to-stage conversion.",
            figure="funnel_cohorts",
            table=cohorts,
        )
    )

    vel = con.execute("select * from marts.mart_pipeline_velocity").df()
    rep.sections.append(
        Section(
            "8. Pipeline velocity",
            "Velocity = (# opportunities x win rate x average won ACV) / average days from "
            "opportunity creation to closed-won. Win rate uses closed deals only. Quarterly rows "
            "group opportunities by creation quarter; recent quarters are right-censored.",
            table=vel.drop(columns=[]),
        )
    )

    funnel = con.execute("select * from marts.fct_funnel_stages").df()
    rep.figures["km_time_to_stage"] = fig_km(funnel, data_end)
    km_rows = []
    for stage in STAGE_COLUMNS:
        km = time_to_stage(funnel, stage, data_end)
        km_rows.append(
            {
                "stage": stage,
                "reached_by_day_90": 1 - km.survival_at(90),
                "reached_by_day_180": 1 - km.survival_at(180),
                "median_days": km.median() if km.median() is not None else float("nan"),
                "events": int(km.events.sum()),
            }
        )
    rep.sections.append(
        Section(
            "9. Time-to-stage (Kaplan-Meier)",
            "Accounts that have not reached a stage by the data cutoff are right-censored rather "
            "than counted as failures, which is what keeps young cohorts from dragging the curve "
            "down. Median is n/a where fewer than half of leads ever reach the stage.",
            figure="km_time_to_stage",
            table=pd.DataFrame(km_rows),
        )
    )
    return rep
